    private val giveUp = Regex("(?<!\\p{L})(?:сдаюсь|не знаю|скажи ответ|какой ответ|ответ скажи|скажи|не помню|без понятия|хватит думать)(?!\\p{L})")
    private val hintAsk = Regex("(?<!\\p{L})(?:подскажи|подсказк[ау]|намекни|намек)(?!\\p{L})")
