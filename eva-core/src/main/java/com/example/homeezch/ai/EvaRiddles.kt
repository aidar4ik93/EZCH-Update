    fun correct(r: Riddle, answer: String): Boolean {
        val words = normalize(answer).split(Regex("[^\\p{L}]+")).filter { it.isNotEmpty() }
        return words.any { w -> r.stems.any { s -> w.startsWith(normalize(s)) } }
    }
    fun wantsGiveUp(t: String) = giveUp.containsMatchIn(normalize(t))
    fun wantsHint(t: String) = hintAsk.containsMatchIn(normalize(t))
    fun wantsStop(t: String) = stop.matches(normalize(t).trimEnd('.', '!', '?'))
    fun wantsMore(t: String) = yes.matches(normalize(t).trimEnd('.', '!', '?'))
